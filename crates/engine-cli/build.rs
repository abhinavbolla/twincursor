//! Bakes a server into `tc-engine` when the build environment names one, so a test build can
//! reach a hosted server with no setup:
//!
//! ```text
//! TWINCURSOR_BUILD_SERVER_URL=wss://… TWINCURSOR_BUILD_API_KEY=… TWINCURSOR_BUILD_API_SECRET=… \
//!   cargo build --release -p twincursor-engine-cli
//! ```
//!
//! Without them, the engine falls back to the local dev server. The values land in a generated
//! file under `OUT_DIR` (never on rustc's command line) and in the binary itself: anyone who has
//! the binary can read them, so a build with a baked secret is only for people you trust with
//! that server. See docs/threat-model.md.

use std::fmt::Write as _;

const VARS: [(&str, &str); 3] = [
    ("URL", "TWINCURSOR_BUILD_SERVER_URL"),
    ("API_KEY", "TWINCURSOR_BUILD_API_KEY"),
    ("API_SECRET", "TWINCURSOR_BUILD_API_SECRET"),
];

fn main() {
    let mut out = String::from("// Generated by build.rs from the build environment.\n");
    for (name, var) in VARS {
        println!("cargo:rerun-if-env-changed={var}");
        let value = std::env::var(var)
            .ok()
            .map(|v| v.trim().to_owned())
            .filter(|v| !v.is_empty());
        let _ = writeln!(out, "pub const {name}: Option<&str> = {value:?};");
    }
    let dir = std::env::var("OUT_DIR").expect("cargo sets OUT_DIR");
    std::fs::write(format!("{dir}/baked.rs"), out).expect("writing baked.rs");
}
